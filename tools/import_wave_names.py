#!/usr/bin/env python3
"""Build device/jv2080_names.js (wave names per wave group) from SR-JV80 board documents.

The wave names come from Roland's board documentation as published on planet-groove.com, which is
Roland's copyright. So the names are imported by the maintainer, not written into the repository by hand:

    python3 -I tools/import_wave_names.py                 # download boards 01-19, write device/jv2080_names.js
    python3 -I tools/import_wave_names.py --from DIR      # use local copies DIR/sr-jv80-NN.txt instead

Internal waves (INT-A / INT-B) can be added from a local text file with lines "A 001 Name" / "B 001 Name":

    python3 -I tools/import_wave_names.py --internal docs/int_waves.txt

Only the WAVEFORM section of each document is used; patch lists and other sections are skipped.
Boards whose document has no wave list are left out (the device then shows only the number).
"""
import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
URL = "http://www.planet-groove.com/roland/sr-jv80-%02d.txt"
UA = "Mozilla/5.0 (Macintosh; Intel Mac OS X 14_0) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/17.0 Safari/605.1.15"
NAME_WIDTH = 12   # the JV shows 12 characters
WAVE_HEADING = re.compile(r"wave\s*form|wave\s+list", re.I)
END_HEADING = re.compile(r"patch\s+list|^\s*patches\s*:|by\s+region|rhythm|copyright|^\s*\*{1,3}\s", re.I)
ENTRY = re.compile(r"^\s*(\d{1,3})\s*[:.]?\s+(\S.*?)\s*$")


def fetch(n, local):
    if local:
        p = Path(local) / ("sr-jv80-%02d.txt" % n)
        return p.read_text(errors="replace") if p.exists() else ""
    req = urllib.request.Request(URL % n, headers={"User-Agent": UA})
    try:
        with urllib.request.urlopen(req, timeout=20) as r:
            return r.read().decode("latin-1")
    except Exception as e:
        print(f"  SR-JV80-{n:02d}: download failed ({e})", file=sys.stderr)
        return ""


def clean(name):
    name = re.sub(r"\s*\*+\s*$", "", name)           # footnote markers
    name = re.sub(r"^\([A-Z]?\d+\)\s*", "", name)    # "(A11) name" style prefixes
    return name[:NAME_WIDTH].rstrip()


def parse_waves(text):
    """number -> name from the first wave section of a board document."""
    waves, inside = {}, False
    for line in text.splitlines():
        if not inside:
            if WAVE_HEADING.search(line) and "document" not in line.lower():
                inside = True
            continue
        if END_HEADING.search(line) and not ENTRY.match(line):
            if waves:
                break
            continue
        m = ENTRY.match(line)
        if m:
            n = int(m.group(1))
            if 1 <= n <= 255 and n not in waves:
                name = clean(m.group(2))
                if name and not name.lower().startswith("name"):
                    waves[n] = name
    return waves


def parse_internal(path):
    groups = {"INT-A": {}, "INT-B": {}}
    for line in Path(path).read_text().splitlines():
        m = re.match(r"^\s*([AB])\s+(\d{1,3})\s+(\S.*?)\s*$", line)
        if m:
            groups["INT-" + m.group(1)][int(m.group(2))] = clean(m.group(3))
    return groups


def render(groups):
    def arr(d):
        top = max(d) if d else 0
        return json.dumps([d.get(i, "") for i in range(1, top + 1)], ensure_ascii=False)
    body = ",\n".join('\t"%s": %s' % (k, arr(v)) for k, v in groups.items() if v)
    return f"""// Wave names per wave group, index 0 = wave 1. GENERATED by tools/import_wave_names.py from Roland's
// board documentation (Roland's copyright); not edited by hand. Empty file = the device shows numbers only.
var JV2080_WAVE_NAMES = {{
{body}
}};

if (typeof module !== "undefined") {{
\tmodule.exports = JV2080_WAVE_NAMES;
}}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--from", dest="local", help="directory with local copies sr-jv80-NN.txt")
    ap.add_argument("--internal", help="text file with INT-A/INT-B names (lines 'A 001 Name')")
    ap.add_argument("--out", default=str(ROOT / "device" / "jv2080_names.js"))
    a = ap.parse_args()
    groups = parse_internal(a.internal) if a.internal else {}
    for n in range(1, 20):
        waves = parse_waves(fetch(n, a.local))
        print(f"  SR-JV80-{n:02d}: {len(waves)} waves" + ("" if waves else " (no wave list)"))
        if waves:
            groups["SR-%02d" % n] = waves
    Path(a.out).write_text(render(groups))
    print(f"wrote {a.out}: {', '.join(groups) or 'no names'}")


if __name__ == "__main__":
    main()
