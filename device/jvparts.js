// The Parts page's bank menus and patch names (one instance, in JV_PERFORM.maxpat).
//
// Bank menus: each part's stored, automatable bank parameter (P<n>Bank, hidden) keeps a fixed list: 0 USER, 1-5
// PR-A..PR-E (4 = the GM bank), 6 CARD, 7..25 expansion board 1..19. The visible menu (P<n>BankView, a Hidden
// parameter) lists only what this JV has: the model's banks and the boards set up on the Setup page, labelled with
// the slot ("XP-A"), like the program block. A stored bank that isn't set up stays selectable, marked.
//
// Patch names (P<n>Name): presets and boards from jv2080_patchnames.js (generated by tools/import_patch_names.py
// from Roland's documents; may be empty), USER patches from the JV itself ("askname n" -> jvreceive.js reads the
// 12-character name of USER:n and answers "username n <name>").
//
// The Part page (JV_PARTEDIT, one per part) shows the same controls, bigger: its copies (Hidden parameters) follow
// the strip ("part <n> <Var> set <v>", "... _parameter_range ...", outlet 1 -> s ---partmirror), and an edit there
// ("edit <n> <Var> <v>", r ---partedit) moves the strip's control, which sends it to the JV and stores it.
//
// inlet 0: "bank <part> <0-25>" (stored menu), "patch <part> <1-255>", "pick <part> <index>" (visible menu),
//          "boards a b c d e f g h", "model 0/1/2", "username <n> <name>",
//          "show <part> <Var> <v>" (a strip control's output), "edit <part> <Var> <v>", "refresh <part>" (Part page)
// outlet 0: "askname <n>" (s ---askname)
// outlet 1: "part <n> <Var> <message...>" for the Part page's copies (s ---partmirror)
// It also draws the device's part buttons (PartSel<n>, main patch) faint for parts that are switched off.

include("jv2080_patchnames.js");

autowatch = 1;
inlets = 1;
outlets = 2;
setinletassist(0, "bank / patch / pick / show / edit <part> ..., refresh, boards, model, username");
setoutletassist(0, "askname n");
setoutletassist(1, "part n Var message for the Part page");

var jsthis = this;
var SLOTS = "ABCDEFGH";
var FIXED = 7;
var KEYS = ["USER", "PR-A", "PR-B", "PR-C", "PR-D", "PR-E", "CARD"];   // names table keys; boards: "SR-01".."SR-19"
// per model (as in jvbank.js): which of the fixed banks exist, the GM bank's label, how many slots
var MODELS = [
	{ fixed: [0, 1, 2, 3, 4, 5, 6], gm: "PR-GM", slots: 8 },
	{ fixed: [0, 1, 2, 3, 4, 6], gm: "PR-D", slots: 4 },
	{ fixed: [0, 1, 2, 3, 4], gm: "PR-D", slots: 4 }
];
var LABELS = ["USER", "PR-A", "PR-B", "PR-C", null, "PR-E", "CARD"];
// the strip controls the Part page copies (P<n><Var>); the bank menu and the name are handled on their own
var MIRRORED = ["On", "Channel", "Patch", "Level", "Pan", "Voices"];

var model = 0;
var slots = [0, 0, 0, 0, 0, 0, 0, 0];
var bank = [];
var number = [];
var items = [];   // per part: stored value for each visible menu entry
var userNames = {};
for (var p = 0; p < 16; p++) {
	bank.push(0);
	number.push(p + 1);
	items.push([]);
}

function loadbang() {
	for (var q = 1; q <= 16; q++) {
		rebuild(q);
	}
}

function anything() {
	var a = arrayfromargs(arguments);
	var part = Math.round(a[0]);
	if (messagename === "username") {
		var words = a.slice(1).join(" ").replace(/\s+$/, "");
		userNames[part] = words;
		for (var q = 1; q <= 16; q++) {
			if (bank[q - 1] === 0 && number[q - 1] === part) {
				showName(q);
			}
		}
		return;
	}
	if (messagename === "boards") {
		for (var i = 0; i < 8; i++) {
			var b = Math.round(a[i] || 0);
			slots[i] = b >= 1 && b <= 19 ? b : 0;
		}
		loadbang();
		return;
	}
	if (messagename === "model") {
		model = MODELS[part] ? part : 0;
		loadbang();
		return;
	}
	if (part < 1 || part > 16) {
		return;
	}
	if (messagename === "refresh") {
		refresh(part);
		return;
	}
	if (messagename === "show") {
		mirror(part, a[1], "set", a[2]);
		if (a[1] === "On") {
			inUse(part, Math.round(a[2]) === 1);
		}
		return;
	}
	if (messagename === "edit") {
		if (a[1] === "BankView") {
			pick(part, Math.round(a[2]));
		} else if (MIRRORED.indexOf(a[1]) >= 0) {
			var ctl = jsthis.patcher.getnamed("P" + part + a[1]);
			if (ctl) {
				ctl.message("float", +a[2]);   // the strip's control sends it and reports back with "show"
			}
		}
		return;
	}
	var v = Math.round(a[1]);
	if (messagename === "bank") {
		bank[part - 1] = v;
		if (items[part - 1].indexOf(v) < 0) {
			rebuild(part);
		} else {
			showMenu(part);
		}
		nameFor(part);
	} else if (messagename === "patch") {
		number[part - 1] = v;
		nameFor(part);
	} else if (messagename === "pick") {
		pick(part, v);
	}
}

function pick(part, index) {
	var value = items[part - 1][index];
	var menu = jsthis.patcher.getnamed("P" + part + "Bank");
	if (value !== undefined && menu) {
		menu.message("int", value);   // the stored menu sends it and reports back with "bank"
	}
}

// the part buttons in the device's page column (PartSel<n>): parts that are switched off are drawn faint
var DIMMED = [0.45, 0.45, 0.45, 0.6], NORMAL = [0.1, 0.1, 0.1, 1.0];
function inUse(part, on) {
	var top = jsthis.patcher.parentpatcher;
	var button = top ? top.getnamed("PartSel" + part) : null;
	if (button) {
		button.message(["textcolor"].concat(on ? NORMAL : DIMMED));
		button.message(["bordercolor"].concat(on ? [0.647, 0.647, 0.647, 1.0] : [0.647, 0.647, 0.647, 0.3]));
	}
}

function mirror(part, name) {
	outlet(1, ["part", part, name].concat(Array.prototype.slice.call(arguments, 2)));
}

// everything the Part page shows for one part (when it gets its part number)
function refresh(part) {
	for (var i = 0; i < MIRRORED.length; i++) {
		var ctl = jsthis.patcher.getnamed("P" + part + MIRRORED[i]);
		if (ctl) {
			var v = ctl.getvalueof();
			mirror(part, MIRRORED[i], "set", v instanceof Array ? v[0] : v);
		}
	}
	rebuild(part);
	showName(part);
}

// the visible menu's entries for one part
function entries(part) {
	var m = MODELS[model], list = [], labels = [];
	for (var i = 0; i < m.fixed.length; i++) {
		list.push(m.fixed[i]);
		labels.push(m.fixed[i] === 4 ? m.gm : LABELS[m.fixed[i]]);
	}
	for (var s = 0; s < m.slots; s++) {
		var value = slots[s] ? FIXED + slots[s] - 1 : -1;
		if (value >= FIXED && list.indexOf(value) < 0) {
			list.push(value);
			labels.push("XP-" + SLOTS.charAt(s));
		}
	}
	var cur = bank[part - 1];
	if (list.indexOf(cur) < 0) {
		list.push(cur);
		labels.push((cur >= FIXED ? "SR-" + pad2(cur - FIXED + 1) : LABELS[cur] || m.gm) + " (n/a)");
	}
	return { list: list, labels: labels };
}

function rebuild(part) {
	var e = entries(part);
	items[part - 1] = e.list;
	var menu = jsthis.patcher.getnamed("P" + part + "BankView");
	if (menu) {
		menu.message(["_parameter_range"].concat(e.labels));
	}
	outlet(1, ["part", part, "BankView", "_parameter_range"].concat(e.labels));
	showMenu(part);
}

function showMenu(part) {
	var i = items[part - 1].indexOf(bank[part - 1]);
	var menu = jsthis.patcher.getnamed("P" + part + "BankView");
	if (i >= 0 && menu) {
		menu.message("set", i);
	}
	if (i >= 0) {
		mirror(part, "BankView", "set", i);
	}
}

// the name of the part's patch: from the table, or for USER patches from the JV
function nameFor(part) {
	var b = bank[part - 1], n = number[part - 1];
	if (b === 0) {
		if (n >= 1 && n <= 128) {
			outlet(0, "askname", n);   // a renamed USER patch should show its new name: ask every time
		}
	}
	showName(part);
}

function name(b, n) {
	if (b === 0) {
		return userNames[n] || "";
	}
	var key = b >= FIXED ? "SR-" + pad2(b - FIXED + 1) : KEYS[b];
	var list = typeof JV2080_PATCH_NAMES !== "undefined" ? JV2080_PATCH_NAMES[key] : null;
	return list && list[n - 1] ? list[n - 1] : "";
}

function showName(part) {
	var label = jsthis.patcher.getnamed("P" + part + "Name");
	var text = name(bank[part - 1], number[part - 1]);
	if (label) {
		label.message("set", text);
	}
	mirror(part, "Name", "set", text);
}

function pad2(n) {
	return (n < 10 ? "0" : "") + n;
}

if (typeof module !== "undefined") {
	module.exports = { entries: entries, name: name };
}
